testthat::test_that("actual current coupon period and settlement boundaries are respected", {
  b <- new_bond(1000, .04, "2026-04-01", "2030-01-01", 2)
  a <- accrual_info(b)
  testthat::expect_equal(a$previous, as.Date("2026-01-01"))
  testthat::expect_equal(a$next_date, as.Date("2026-07-01"))
  testthat::expect_equal(a$accrued, 20 * 90 / 181)
  testthat::expect_true(all(bond_cashflows(b)$payment_date > b$settlement))
  b$settlement <- as.Date("2026-07-01")
  testthat::expect_equal(accrual_info(b)$accrued, 0)
  testthat::expect_equal(bond_cashflows(b)$payment_date[1], as.Date("2027-01-01"))
})
testthat::test_that("end of month and leap dates remain anchored", {
  testthat::expect_equal(shift_months(as.Date("2028-08-31"), -6), as.Date("2028-02-29"))
  testthat::expect_equal(shift_months(as.Date("2028-08-30"), -12), as.Date("2027-08-30"))
  b <- new_bond(100, .04, "2026-03-01", "2028-08-31", 4)
  dates <- coupon_schedule(b)
  testthat::expect_true(as.Date("2027-08-31") %in% dates)
  testthat::expect_equal(sum(bond_cashflows(b)$principal), 100)
})
testthat::test_that("invalid parameters fail clearly", {
  testthat::expect_error(new_bond(0, .04, "2026-01-01", "2030-01-01"))
  testthat::expect_error(new_bond(100, .04, "2030-01-01", "2030-01-01"))
  testthat::expect_error(new_bond(100, .04, "2026-01-01", "2030-01-01", 3))
})
